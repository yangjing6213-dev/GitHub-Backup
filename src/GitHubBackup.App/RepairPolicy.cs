namespace GitHubBackup.App;

internal static class RepairPolicy
{
    internal static bool IsRepairable(string code) => code is
        "PREFLIGHT_PRIVATE_ROOT_ACL_UNSAFE" or "PREFLIGHT_PRIVATE_OWNER_UNSAFE" or "PREFLIGHT_PRIVATE_NULL_DACL_UNSAFE" or "PREFLIGHT_PRIVATE_READ_ACL_UNSAFE"
        or "LOCK_PATH_OWNER_UNSAFE" or "LOCK_PATH_NULL_DACL_UNSAFE" or "LOCK_PATH_READ_ACL_UNSAFE" or "LOCK_PATH_WRITE_ACL_UNSAFE"
        or "MIRROR_SOURCE_OWNER_UNSAFE" or "MIRROR_SOURCE_NULL_DACL_UNSAFE" or "MIRROR_SOURCE_READ_ACL_UNSAFE" or "MIRROR_SOURCE_WRITE_ACL_UNSAFE"
        or "METADATA_SOURCE_OWNER_UNSAFE" or "METADATA_SOURCE_NULL_DACL_UNSAFE" or "METADATA_SOURCE_READ_ACL_UNSAFE" or "METADATA_SOURCE_WRITE_ACL_UNSAFE"
        or "RELEASE_SOURCE_OWNER_UNSAFE" or "RELEASE_SOURCE_NULL_DACL_UNSAFE" or "RELEASE_SOURCE_READ_ACL_UNSAFE" or "RELEASE_SOURCE_WRITE_ACL_UNSAFE"
        or "MANIFEST_OWNER_UNSAFE" or "MANIFEST_NULL_DACL_UNSAFE" or "MANIFEST_READ_ACL_UNSAFE" or "MANIFEST_WRITE_ACL_UNSAFE";
}
